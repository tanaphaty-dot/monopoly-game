package model.entity;

/**
 * ช่วยบอกว่าคนเล่นกำลังอยู่ในสถานะตัดสินใจเรื่องไรอยู่
 * 
 * Enum กำหนดการกระทำที่ผู้เล่นกำลังรอดำเนินการ 
 * @author เดียร์ entity-player
 */
public enum PendingAction {
    NONE,             // ไม่มีแอ็กชันค้าง
    BUY_CITY,         // ตกเมืองว่าง -> รอตอบว่าจะซื้อไหม
    PAY_RENT,         // ตกเมืองคนอื่น -> รอจ่ายค่าผ่านทาง
    SIEGE_OR_PAY,     // ตกเมืองคนอื่น -> รอตอบว่าจะ "ตีเมือง" หรือ "จ่ายค่าผ่านทาง"
    DRAW_CARD,        // ตกช่องเหตุการณ์ -> รอจั่วการ์ด
    IN_JAIL           // อยู่ในคุก -> รอติดคุกหรือจ่ายเงินประกัน
}